export function findKnowledge(id: string): KnowledgeEntry | undefined {
  return KNOWLEDGE_ENTRIES.find((e) => e.id === id)
}

export function searchKnowledge(query: string): KnowledgeEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return KNOWLEDGE_ENTRIES
  return KNOWLEDGE_ENTRIES.filter((e) =>
    [e.title, e.titleEn, e.plain, e.definition, ...e.formulas, ...e.applications, ...e.questions.map((x) => x.q)]
      .join(' ')
      .toLowerCase()
      .includes(q),
  )
}
